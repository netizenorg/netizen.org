/* netizen.org — desktop splash reveal
 *
 * Replaces NetizenASCIISplash's own hover/click behaviour (click = asciify,
 * dblclick = next image, in netizen-ascii-splash.js:77-102) on the home
 * splash. Loaded unconditionally alongside the other desktop scripts; see
 * the boot section at the bottom for how it waits for `splash` to exist.
 *
 * WHAT IT DOES (inverts NetizenASCIISplash's original behaviour)
 *   original : base canvas holds the clean photo; the cursor ADDS ascii on top.
 *   this     : the photo is covered in real syrup; the cursor ERASES it away,
 *              revealing the photograph through the hole.
 *
 *   - cover is generated by the actual NetizenSyrupImage class using the site's
 *     own syrupSettings, so the splash matches every other image on the site
 *     instead of using its own private ascii dialect.
 *   - the erase is quantised to the ascii cell grid (blocky), never a smooth arc.
 *   - the brush shape is the netizen.org wordmark, rendered to a mask.
 *   - on load the wordmark stamps centred, holds, then dissolves.
 *   - after ~2.6s of no pointer movement the mark detaches and drifts DVD-logo
 *     style, flipping polarity (hole <-> inverted) on every wall hit so it can
 *     never sit invisible for long. Needs no input at all -- see the idle
 *     drift section below for why that specifically matters.
 *   - on click the background image advances and whatever is currently erased
 *     resolves — by default back into the clean centred wordmark.
 *
 * CALIBRATION (found by eye, these matter)
 *   textPx/cell ratio    — strokes need to be 2-3 cells wide or the wordmark
 *                          mushes into noise. sizeFor() derives both from
 *                          canvas width so this ratio holds at any size, not
 *                          just the ~910px window this was tuned against.
 *   resolveMs 900         — batching is duration-targeted. A fixed batch size made
 *                           a 2600-cell scribble take ~9s while 191 cells took <1s.
 *   every cell animates exactly ONCE per gesture. Re-randomising cells each frame
 *   reads as a strobe and is a genuine flash-seizure risk (WCAG 2.3.1 caps at 3/s).
 *
 * SETTLED CHOICES (arrived at by comparison, don't relitigate blind)
 *   click fx = 'recover'  — the erased mess resolves back into the centred
 *     wordmark. 'replace' fills holes with syrup fragments but gives up the
 *     "returns to its own name" gesture; 'explode' is nice but reads as
 *     spectacle rather than consequence. Both are still in the code.
 *   Rejected outright: per-frame random noise/scramble. Re-randomising cells
 *     every frame strobes, which is a flash-seizure risk (WCAG 2.3.1, 3/sec).
 *     Every cell animates exactly ONCE per gesture — keep it that way.
 *
 * REMAINING LIMITATION
 *   the syrup rebuild on image change is async and variable (~130ms locally);
 *   if it lags on a slow connection you get a beat of bare, untreated photo
 *   before the new cover lands. Not addressed -- worth knowing if the click
 *   response ever feels laggy on a real network.
 */
function bootSplashReveal () {
  // desktop.js's main() is async (it awaits loadData() before constructing
  // `splash`), so this script's own <script> tag can easily finish parsing
  // before window.splash exists. Poll rather than assume load order.
  //
  // splash.canvas exists as soon as NetizenASCIISplash.init() runs, but it's
  // only sized (resizeCanvas()) once the splash image finishes loading --
  // stuck at the browser's 300x150 default until then. Also wait on
  // splash.img (set in the same synchronous step right before
  // resizeCanvas(), see netizen-ascii-splash.js), or a slow/uncached image
  // load loses this race and W/H below get baked in at 300x150 -- a tiny
  // canvas pinned top-left instead of full screen, and it stays that way
  // until the window is manually resized.
  if (typeof splash === 'undefined' || !splash || !splash.canvas || !splash.img) {
    setTimeout(bootSplashReveal, 120)
    return
  }
  if (window.__lab) window.__lab.destroy();

  const S = splash;
  const container = document.getElementById('splash-canvas');
  const base = S.canvas;
  let W = base.width, H = base.height;
  const key = (x, y) => x + '_' + y;

  // textPx 150 / cell 12 was tuned by eye at ~910px canvas width (0.1648 of
  // W). Strokes need to stay 2-3 cells wide or the wordmark mushes into
  // noise on cold-load's default viewport -- keep that RATIO, not the
  // absolute numbers, so it holds up narrow or wide. sizeFor() is reused by
  // the resize handler further down.
  const sizeFor = w => {
    const textPx = Math.round(Math.max(70, Math.min(240, w * 0.1648)));
    return { textPx, cell: Math.max(6, Math.round(textPx / 12.5)) };
  };
  const initial = sizeFor(W);

  const L = {
    cell: initial.cell, textPx: initial.textPx, radius: 200,
    resolveMs: 900, introHold: 2600,
    text: 'netizen.org', shape: 'text', mode: 'recover',
    holes: new Map(), timers: [], overlay: null, cover: null, raf: null,
    active: true, busy: false
  };
  S.duration = 1400;

  /* ---------- syrup cover ------------------------------------------------ */

  const host = document.createElement('div');
  Object.assign(host.style, { position: 'fixed', left: '-99999px', top: '0',
    width: W + 'px', height: H + 'px', overflow: 'hidden' });
  document.body.appendChild(host);
  L.host = host;

  L.rebuildSyrup = path => new Promise(resolve => {
    host.innerHTML = '';
    new NetizenSyrupImage({
      image: path, ele: host, colors: ['#99ffcc', '#993399'],
      huffhack: { ...syrupSettings.huffhack }, dither: { ...syrupSettings.dither },
      pixelate: { ...syrupSettings.pixelate }, ascii: { ...syrupSettings.ascii }
    });
    let n = 0;
    const poll = setInterval(() => {
      const imgs = [...host.querySelectorAll('img')].filter(i => i.complete && i.naturalWidth);
      if (imgs.length >= 3 || ++n > 60) {
        clearInterval(poll);
        const c = document.createElement('canvas');
        c.width = W; c.height = H;
        const cx = c.getContext('2d');
        cx.fillStyle = '#000'; cx.fillRect(0, 0, W, H);
        imgs.sort((a, b) => (+a.style.zIndex || 0) - (+b.style.zIndex || 0))
            .forEach(im => { cx.globalAlpha = parseFloat(im.style.opacity || 1); cx.drawImage(im, 0, 0, W, H); });
        cx.globalAlpha = 1;
        resolve(c);
      }
    }, 100);
  });

  /* ---------- brush shapes ----------------------------------------------- */

  L.buildMask = () => {
    const probe = document.createElement('canvas').getContext('2d');
    const font = `700 ${L.textPx}px "Zen Maru Gothic", ui-sans-serif, sans-serif`;
    probe.font = font;
    const w = Math.ceil(probe.measureText(L.text).width) + 10;
    const h = Math.ceil(L.textPx * 1.45);
    const c = document.createElement('canvas');
    c.width = w; c.height = h;
    const cx = c.getContext('2d');
    cx.font = font; cx.textBaseline = 'middle'; cx.fillStyle = '#fff';
    cx.fillText(L.text, 5, h / 2);
    L.mask = { w, h, data: cx.getImageData(0, 0, w, h).data };
    return L.mask;
  };

  L.cellsInText = (x, y) => {
    if (!L.mask) L.buildMask();
    const { w, h, data } = L.mask, fs = L.cell, out = [];
    const ox = x - w / 2, oy = y - h / 2;
    for (let r = Math.max(0, Math.floor(oy / fs)); r < Math.ceil((oy + h) / fs); r++) {
      for (let c = Math.max(0, Math.floor(ox / fs)); c < Math.ceil((ox + w) / fs); c++) {
        const mx = Math.floor(c * fs + fs / 2 - ox), my = Math.floor(r * fs + fs / 2 - oy);
        if (mx < 0 || my < 0 || mx >= w || my >= h) continue;
        if (data[(my * w + mx) * 4 + 3] > 128) out.push([c * fs, r * fs]);
      }
    }
    return out;
  };

  L.cellsInRadius = (x, y) => {
    const fs = L.cell, r = L.radius, out = [];
    for (let rw = Math.max(0, Math.floor((y - r) / fs)); rw < Math.min(Math.ceil((y + r) / fs), Math.ceil(H / fs)); rw++) {
      for (let cl = Math.max(0, Math.floor((x - r) / fs)); cl < Math.min(Math.ceil((x + r) / fs), Math.ceil(W / fs)); cl++) {
        const cx = cl * fs + fs / 2, cy = rw * fs + fs / 2;
        if ((cx - x) ** 2 + (cy - y) ** 2 <= r * r) out.push([cl * fs, rw * fs]);
      }
    }
    return out;
  };

  /* ---------- one-shot batched cell ops (no strobe) ---------------------- */

  L.batched = (ops, ms = L.resolveMs, interval = 22) => new Promise(res => {
    const list = ops.slice();
    for (let i = list.length - 1; i > 0; i--) { const j = (Math.random() * (i + 1)) | 0;[list[i], list[j]] = [list[j], list[i]]; }
    const steps = Math.max(1, Math.round(ms / interval));
    const batch = Math.ceil(list.length / steps);   // duration-targeted, not fixed
    for (let s = 0; s < steps; s++) {
      L.timers.push(setTimeout(() => {
        for (let k = s * batch; k < Math.min((s + 1) * batch, list.length); k++) list[k]();
        if (s === steps - 1) res();
      }, s * interval));
    }
  });

  /* ---------- overlay + brush -------------------------------------------- */

  function buildOverlay() {
    S.clearStack(); S.drawImageCover(); S.locked = true;
    const o = document.createElement('canvas');
    o.width = W; o.height = H;
    Object.assign(o.style, { position: 'fixed', top: '0', left: '0', pointerEvents: 'none' });
    container.appendChild(o);
    L.overlay = o;
    o.getContext('2d').drawImage(L.cover, 0, 0);
  }

  L.onMove = e => {
    if (!L.active || L.busy || !L.overlay || !L.cover) return;
    const r = base.getBoundingClientRect();
    const x = e.clientX - r.left, y = e.clientY - r.top;
    if (x < -400 || y < -200 || x > W + 400 || y > H + 200) return;
    L.lastMove = performance.now();
    if (L.drift) L.stopDrift();          // pointer wins; idle drift yields
    const fs = L.cell, ctx = L.overlay.getContext('2d');
    const cells = L.shape === 'text' ? L.cellsInText(x, y) : L.cellsInRadius(x, y);
    cells.forEach(([cx, cy]) => { ctx.clearRect(cx, cy, fs, fs); L.holes.set(key(cx, cy), [cx, cy]); });
    L.timers.push(setTimeout(() => {
      if (!L.overlay || !L.cover || L.busy) return;
      const c2 = L.overlay.getContext('2d');
      cells.forEach(([cx, cy]) => {
        c2.drawImage(L.cover, cx, cy, fs, fs, cx, cy, fs, fs);
        L.holes.delete(key(cx, cy));
      });
    }, S.duration));
  };

  L.stampIntro = () => {
    if (!L.overlay || !L.cover) return 'not ready';
    const ctx = L.overlay.getContext('2d');
    ctx.drawImage(L.cover, 0, 0);
    L.holes.clear();
    const cells = L.cellsInText(W / 2, H / 2);
    cells.forEach(([x, y]) => { ctx.clearRect(x, y, L.cell, L.cell); L.holes.set(key(x, y), [x, y]); });
    L.timers.push(setTimeout(() => {
      const ops = cells.map(([x, y]) => () => {
        L.overlay.getContext('2d').drawImage(L.cover, x, y, L.cell, L.cell, x, y, L.cell, L.cell);
        L.holes.delete(key(x, y));
      });
      L.batched(ops, 850);
    }, L.introHold));
    return cells.length + ' cells';
  };

  /* ---------- idle drift: the wordmark bounces like a DVD logo ------------
   * After idleMs of no pointer movement the mark detaches and drifts, flipping
   * polarity on every wall hit:
   *
   *   negative  clearRect        -> the photo shows through the letterforms
   *   positive  difference-white -> the letterforms invert whatever syrup is
   *                                 under them
   *
   * Polarity is what keeps it readable. A hole is invisible over a dark photo
   * and an inverted mark is invisible over flat mid-grey, but the two failure
   * cases don't overlap — alternating means it can never disappear for long.
   * Inverting (rather than painting a fixed colour) also guarantees contrast
   * against whatever it happens to be sitting on.                            */

  L.idleMs = 2600;
  L.driftSpeed = 0.55;
  L.drift = null;
  L.lastMove = performance.now();

  L.startDrift = () => {
    if (L.drift || !L.overlay || !L.cover || L.busy) return;
    const m = L.mask || L.buildMask();
    const a = Math.random() * Math.PI * 2;
    L.drift = {
      x: W / 2, y: H / 2,
      vx: Math.cos(a) * L.driftSpeed * 60,
      vy: Math.sin(a) * L.driftSpeed * 60,
      polarity: 0, t: performance.now()
    };
    const step = () => {
      if (!L.drift) return;
      const d = L.drift, now = performance.now();
      const dt = Math.min(48, now - d.t) / 16.67;   // clamp so tab-switches don't teleport it
      d.t = now;
      d.x += d.vx * dt * 0.06;
      d.y += d.vy * dt * 0.06;

      const hw = m.w / 2, hh = m.h / 2;
      if (d.x - hw < 0)      { d.x = hw;      d.vx = Math.abs(d.vx);  d.polarity ^= 1; }
      if (d.x + hw > W)      { d.x = W - hw;  d.vx = -Math.abs(d.vx); d.polarity ^= 1; }
      if (d.y - hh < 0)      { d.y = hh;      d.vy = Math.abs(d.vy);  d.polarity ^= 1; }
      if (d.y + hh > H)      { d.y = H - hh;  d.vy = -Math.abs(d.vy); d.polarity ^= 1; }

      const ctx = L.overlay.getContext('2d');
      ctx.drawImage(L.cover, 0, 0);                 // repaint syrup, then punch the mark
      const cells = L.cellsInText(d.x, d.y);
      L.holes.clear();
      if (d.polarity === 0) {
        cells.forEach(([x, y]) => { ctx.clearRect(x, y, L.cell, L.cell); L.holes.set(key(x, y), [x, y]); });
      } else {
        ctx.save();
        ctx.globalCompositeOperation = 'difference';
        ctx.fillStyle = '#fff';
        cells.forEach(([x, y]) => ctx.fillRect(x, y, L.cell, L.cell));
        ctx.restore();
        cells.forEach(([x, y]) => L.holes.set(key(x, y), [x, y]));   // clickable either way
      }
      L.drift.raf = requestAnimationFrame(step);
    };
    step();
  };

  /* keepHoles: onClick needs the drifting mark's cells to resolve from, so it
   * stops the drift without wiping what was erased. */
  L.stopDrift = (keepHoles) => {
    if (!L.drift) return;
    cancelAnimationFrame(L.drift.raf);
    L.drift = null;
    if (!keepHoles && L.overlay && L.cover) {
      L.overlay.getContext('2d').drawImage(L.cover, 0, 0);
      L.holes.clear();
    }
  };

  L.idleWatch = setInterval(() => {
    if (L.busy || !L.cover) return;
    if (!L.drift && performance.now() - L.lastMove > L.idleMs) L.startDrift();
  }, 300);

  /* ---------- click: advance image + resolve the erased region ----------- */

  L.onClick = async () => {
    if (L.busy || !L.cover || !L.holes.size) return;
    L.busy = true;
    L.stopDrift(true);                    // freeze it, but keep the cells to resolve from
    L.lastMove = performance.now();
    const fs = L.cell, ctx = L.overlay.getContext('2d'), oldCover = L.cover;

    const swap = (async () => {
      if (S.imageList) {
        S.currentIndex = (S.currentIndex + 1) % S.imageList.length;
        S.imagePath = S.imageList[S.currentIndex];
        S.img = await S.loadImage(S.imagePath);
        S.drawImageCover();
      }
      return L.rebuildSyrup(S.imagePath);
    })();

    if (L.mode === 'recover') {
      // whatever is erased resolves into the clean centred wordmark
      const target = new Map();
      L.cellsInText(W / 2, H / 2).forEach(([x, y]) => target.set(key(x, y), [x, y]));
      const ops = [];
      L.holes.forEach(([x, y], k) => { if (!target.has(k)) ops.push(() => { ctx.drawImage(oldCover, x, y, fs, fs, x, y, fs, fs); L.holes.delete(k); }); });
      target.forEach(([x, y], k) => { if (!L.holes.has(k)) ops.push(() => { ctx.clearRect(x, y, fs, fs); L.holes.set(k, [x, y]); }); });
      await L.batched(ops);
    } else if (L.mode === 'replace') {
      const ops = [...L.holes.values()].map(([x, y]) => () => {
        const rx = Math.floor(Math.random() * (W / fs)) * fs, ry = Math.floor(Math.random() * (H / fs)) * fs;
        ctx.drawImage(oldCover, rx, ry, fs, fs, x, y, fs, fs);
        L.holes.delete(key(x, y));
      });
      await L.batched(ops);
    } else { // explode — continuous motion, not random flicker
      const cells = [...L.holes.values()];
      const parts = cells.map(([x, y]) => ({ ox: x, oy: y, x, y, vx: (Math.random() - .5) * 4, vy: (Math.random() - .5) * 4 - 1 }));
      await new Promise(res => {
        let t = 0; const F = 32;
        const tick = () => {
          t++;
          ctx.drawImage(oldCover, 0, 0);
          cells.forEach(([x, y]) => ctx.clearRect(x, y, fs, fs));
          parts.forEach(p => {
            p.vy += .18; p.x += p.vx; p.y += p.vy;
            ctx.save(); ctx.globalAlpha = Math.max(0, 1 - t / F);
            ctx.drawImage(oldCover, p.ox, p.oy, fs, fs, p.x, p.y, fs, fs); ctx.restore();
          });
          t < F ? (L.raf = requestAnimationFrame(tick)) : res();
        };
        tick();
      });
      L.holes.clear();
    }

    L.cover = await swap;
    ctx.drawImage(L.cover, 0, 0);
    L.holes.forEach(([x, y]) => ctx.clearRect(x, y, fs, fs));  // keep the mark open
    L.busy = false;
  };

  // e.target check, not just coordinate bounds: the header, nav pills, and
  // splash credit all sit visually inside the canvas's own bounding rect (the
  // canvas fills the top of the page, they float over it). A coordinate-only
  // check would fire this on every nav click and every credit click too --
  // advancing the image and resolving the mark at the exact moment someone
  // navigates away. Only a click that actually lands ON the canvas counts.
  L.onClickBound = e => {
    if (e.target !== base) return;
    L.onClick();
  };

  /* ---------- keep the splash alive on interior pages -------------------- */
  /* NetizenNav._activate() (netizen-nav.js:23) sets #splash-canvas opacity to 0
   * on every interior page, which kills the reveal entirely. Keep it running
   * underneath instead. Two parts are needed:
   *   1. don't zero the opacity
   *   2. #content > div is solid rgb(0,0,0) and occludes it — the cells need
   *      alpha, NOT #content itself (that one is transparent already).       */

  L.keepSplash = true;
  L.splashOpacity = 1;
  L.contentAlpha = 0.85;      // below ~0.6 the body copy starts to struggle

  const cstyle = document.createElement('style');
  cstyle.id = '__labContent';
  document.head.appendChild(cstyle);

  /* Only the COPY cell gets the scrim.
   *
   * Detect it structurally, never by colour. The #content > div cells all start
   * as var(--prim-b) and are painted afterwards from window.colors (the brand's
   * column-1/column-3 pairing), re-picked per section — so any colour-based test
   * races the paint and mislabels all three as "black copy cells". That's what
   * flattened the Initiatives sidebar: it went mint -> translucent black and its
   * links became unreadable over live syrup.
   *
   *   cell with .sub-nav-item  -> sidebar,          leave alone
   *   cell with .content-copy  -> body copy,        scrim this one
   *   empty cell               -> decorative block, leave alone
   *
   * The copy cell is always var(--prim-b) by design, so restoring is exact and
   * we never need to cache the randomised colours. */
  /* Applied as a CLASS, never as an inline style. The cells are re-rendered on
   * every section change and the markup is briefly in flux, so a pass can fire
   * while the copy hasn't landed in its final cell yet and tag the wrong one.
   * With inline styles that mistake is permanent — it overwrites the site's
   * randomised colour and there's no way to recover it. With a class, removing
   * it restores whatever the site painted, so a mistimed pass is self-healing
   * and the next pass corrects it. */
  L.applyContent = () => {
    cstyle.textContent = L.keepSplash
      ? `#content { background: transparent !important; }
         #content > div.__labCopy { background: rgba(0,0,0,${L.contentAlpha}) !important; }`
      : '';
    const c = document.getElementById('content');
    if (!c) return;
    [...c.children].forEach(k => k.classList.remove('__labCopy'));
    if (!L.keepSplash) return;
    // exclude .sub-nav explicitly: mid-transition the sidebar transiently holds
    // a .cell-content before the copy lands in its real cell, which is enough to
    // mis-tag it and briefly darken the sidebar during the switch.
    //
    // .case-study is NOT excluded (it briefly was): load-case-study.js used to
    // flip that cell to a white background + black text, the opposite scheme
    // from About/Support, which made the scrim's black paint text that was
    // also black. Now that load-case-study.js matches the black-bg/white-text
    // scheme everywhere else, the scrim is consistent here too.
    const copy = [...c.children].find(k =>
      !k.classList.contains('sub-nav') &&
      k.querySelector('.cell-content, .content-copy'));
    if (copy) copy.classList.add('__labCopy');
  };
  L.applyContent();

  if (typeof nav !== 'undefined' && nav && nav._activate) {
    L.__origActivate = nav._activate.bind(nav);
    nav._activate = function (sec) {
      L.__origActivate(sec);
      if (L.keepSplash) container.style.opacity = L.splashOpacity;
      L.applyContent();
    };
  }

  /* Timed passes can't do this: the cells re-render asynchronously and rapid
   * section switching overlaps renders, so any fixed delay eventually samples
   * mid-flux and tags the wrong cell. Watch the DOM instead and re-apply
   * whenever it settles — combined with class-based application (reversible),
   * this converges on the right cell no matter how the renders interleave. */
  const contentEl = document.getElementById('content');
  if (contentEl && 'MutationObserver' in window) {
    let deb;
    L.observer = new MutationObserver(() => {
      clearTimeout(deb);
      deb = setTimeout(L.applyContent, 80);
    });
    // NB: deliberately not watching `class` — applyContent toggles .__labCopy,
    // which would retrigger the observer and churn forever.
    L.observer.observe(contentEl, { childList: true, subtree: true, attributes: true, attributeFilter: ['style'] });
  }

  /* ---------- resize --------------------------------------------------------
   * NetizenASCIISplash.resizeCanvas() (netizen-ascii-splash.js:63) already
   * resizes `base` itself on window resize. What it doesn't know about is
   * L.overlay (a second canvas we layered on top) or L.cover (a cached bitmap
   * baked at the OLD dimensions) -- left alone, a resize desyncs the overlay
   * from the canvas entirely. Debounced: a syrup rebuild is the expensive part
   * here (~130ms), not worth paying on every intermediate resize frame while
   * someone's actively dragging a window edge. */
  let resizeTimer;
  L.handleResize = () => {
    clearTimeout(resizeTimer);
    resizeTimer = setTimeout(async () => {
      if (!L.cover) return;
      L.stopDrift();
      W = base.width; H = base.height;
      // NetizenSyrupImage scales each layer against host's rendered size
      // (container.clientWidth/Height), not against a passed-in W/H -- if
      // this stays stale the new syrup cover renders at the old scale.
      host.style.width = W + 'px'; host.style.height = H + 'px';
      const s = sizeFor(W);
      L.textPx = s.textPx; L.cell = s.cell;
      L.buildMask();
      L.overlay.width = W; L.overlay.height = H;
      L.holes.clear();
      L.cover = await L.rebuildSyrup(S.imagePath);
      L.overlay.getContext('2d').drawImage(L.cover, 0, 0);
    }, 250);
  };
  window.addEventListener('resize', L.handleResize);

  /* ---------- scroll behaviour ------------------------------------------- */

  L.setPush = on => {
    container.style.position = on ? 'relative' : 'fixed';
    base.style.position = on ? 'relative' : 'fixed';
    if (on) { base.style.top = ''; base.style.left = ''; }
    else { base.style.top = '0'; base.style.left = '0'; }
    if (L.overlay) { L.overlay.style.position = on ? 'absolute' : 'fixed'; L.overlay.style.top = '0px'; L.overlay.style.left = '0px'; }
  };

  /* ---------- tuning ------------------------------------------------------
   * No on-screen panel — the values below are settled. Everything is still
   * reachable from the console on the live instance if you want to poke at it:
   *
   *   __lab.cell = 12            block size of the erase grid
   *   __lab.textPx = 150         wordmark size (keep strokes 2-3 cells wide)
   *   __lab.buildMask()          re-render the brush after changing textPx
   *   __lab.radius = 200         circle brush size
   *   __lab.shape = 'circle'     'text' | 'circle'
   *   __lab.mode = 'explode'     'recover' | 'replace' | 'explode'
   *   __lab.contentAlpha = 0.85  interior-page scrim; __lab.applyContent() after
   *   __lab.keepSplash = false   stop the splash persisting on interior pages
   *   __lab.setPush(true)        unpin the splash so it scrolls away
   *   __lab.stampIntro()         replay the centred wordmark
   *   __lab.destroy()            remove the whole thing
   */

  /* ---------- teardown --------------------------------------------------- */

  L.destroy = () => {
    L.owns = false;
    if (L.__origStart) S.start = L.__origStart;   // hand the splash back
    if (L.__origActivate) nav._activate = L.__origActivate;
    L.observer?.disconnect();
    L.keepSplash = false; L.applyContent();       // drops .__labCopy everywhere
    cstyle.remove();
    container.style.opacity = '';
    L.stopDrift();
    clearInterval(L.idleWatch);
    L.timers.forEach(clearTimeout);
    clearInterval(L.guard);
    if (L.raf) cancelAnimationFrame(L.raf);
    L.overlay?.remove(); host.remove();
    window.removeEventListener('mousemove', L.onMove);
    window.removeEventListener('click', L.onClickBound);
    window.removeEventListener('resize', L.handleResize);
    clearTimeout(resizeTimer);
    L.setPush(false);
    S.locked = false; S.clearStack(); S.drawImageCover();
    window.__lab = null;
  };

  /* ---------- boot ------------------------------------------------------- */

  // Navigating to an interior page and back calls showHome() -> splash.start()
  // (desktop.js:116), which sets locked = false and revives the native ascii-on-
  // hover effect underneath this one.
  //
  // Polling for this is NOT enough: between start() and the next poll tick, any
  // mousemove draws the old black/white ascii circles and they visibly flash.
  // So take ownership of start() itself — deterministic, no window.
  //
  // NB: overriding S.onHover does nothing. init() registers the listener as
  // this.onHover.bind(this), capturing the original reference at construction,
  // so a later reassignment is never called. Holding `locked` true is what
  // actually suppresses it, because onHover re-checks this.locked on every call.
  L.owns = true;
  L.__origStart = S.start.bind(S);
  S.start = () => { if (!L.owns) L.__origStart(); else S.locked = true; };

  // slow backstop only, for anything that sets locked directly
  L.reassert = () => {
    if (!L.overlay || !L.cover || L.busy) return;
    if (S.locked) return;
    S.clearStack(); S.drawImageCover(); S.locked = true;
    L.overlay.getContext('2d').drawImage(L.cover, 0, 0);
    L.holes.forEach(([x, y]) => L.overlay.getContext('2d').clearRect(x, y, L.cell, L.cell));
  };

  L.buildMask();
  L.rebuildSyrup(S.imagePath).then(cover => {
    L.cover = cover;
    buildOverlay();
    window.addEventListener('mousemove', L.onMove);
    window.addEventListener('click', L.onClickBound);
    L.stampIntro();
    L.guard = setInterval(L.reassert, 1000);
  });

  window.__lab = L;
}

